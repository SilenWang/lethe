"""Generate the P0 fidelity corpus from the VYB-2671 enhanced seeds.

90 files: 30 docx + 30 xlsx + 30 pptx.  Every file is generated by this script
(``GENERATOR_VERSION`` is recorded in ``corpus/manifest.csv``) and immediately
re-opened to prove the elements are in the OOXML, not just in the file name.

Seeds (downloaded from VYB-2669 / VYB-2671 attachments):

* ``corpus/seeds/docx-02-enhanced.docx`` — comments+authors, header/footer,
  footnotes/endnotes, text box, revisions, merged cells, media.  The generator
  adds the missing hyperlink, content control and chart.
* ``corpus/seeds/pptx-02-enhanced.pptx`` — comments+authors, text box, merged
  cells, media, hidden slide, notes, master text.  The generator adds the
  missing footer placeholder, hyperlink and chart.
* xlsx is rebuilt compactly with openpyxl (the 1.75MB dashboard seed times 30
  would be 52MB of near-duplicate data); it keeps the same element set plus
  header/footer, hyperlink, text box, hidden sheet, media and chart.

Run ``pixi run corpus`` and then ``pixi run fidelity-corpus``.
"""

from __future__ import annotations

import csv
import hashlib
import io
import sys
import zipfile
from pathlib import Path
from xml.sax.saxutils import escape

from lxml import etree
from openpyxl import Workbook
from openpyxl.chart import BarChart, Reference
from openpyxl.comments import Comment
from openpyxl.drawing.image import Image as XLImage
from PIL import Image as PILImage

REPO = Path(__file__).resolve().parent.parent
CORPUS = REPO / "corpus"
SEEDS = CORPUS / "seeds"
GENERATOR_VERSION = "1.0.0"
N = 30

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"
PKG_REL = "http://schemas.openxmlformats.org/package/2006/relationships"
CT = "http://schemas.openxmlformats.org/package/2006/content-types"
P = "http://schemas.openxmlformats.org/presentationml/2006/main"
A = "http://schemas.openxmlformats.org/drawingml/2006/main"
C = "http://schemas.openxmlformats.org/drawingml/2006/chart"
XDR = "http://schemas.openxmlformats.org/drawingml/2006/spreadsheetDrawing"

CHART_XML = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<c:chartSpace xmlns:c="{C}" xmlns:a="{A}" xmlns:r="{R}">
  <c:chart>
    <c:plotArea>
      <c:layout/>
      <c:barChart>
        <c:barDir val="col"/><c:grouping val="clustered"/><c:varyColors val="0"/>
        <c:ser><c:idx val="0"/><c:order val="0"/>
          <c:tx><c:strRef><c:f>Data!$B$1</c:f></c:strRef></c:tx>
          <c:cat><c:strRef><c:f>Data!$A$2:$A$5</c:f></c:strRef></c:cat>
          <c:val><c:numRef><c:f>Data!$B$2:$B$5</c:f></c:numRef></c:val>
        </c:ser>
        <c:axId val="111111111"/><c:axId val="222222222"/>
      </c:barChart>
      <c:catAx><c:axId val="111111111"/><c:scaling><c:orientation val="minMax"/></c:scaling>
        <c:delete val="0"/><c:axPos val="b"/><c:crossAx val="222222222"/></c:catAx>
      <c:valAx><c:axId val="222222222"/><c:scaling><c:orientation val="minMax"/></c:scaling>
        <c:delete val="0"/><c:axPos val="l"/><c:crossAx val="111111111"/></c:valAx>
    </c:plotArea>
    <c:plotVisOnly val="1"/>
  </c:chart>
</c:chartSpace>
"""


def normalize_zip(data: bytes) -> bytes:
    """Rewrite every entry with a fixed timestamp so hashes are reproducible."""
    out = io.BytesIO()
    with zipfile.ZipFile(io.BytesIO(data)) as src, zipfile.ZipFile(out, "w") as dst:
        for info in src.infolist():
            zi = zipfile.ZipInfo(info.filename, date_time=(2026, 1, 1, 0, 0, 0))
            zi.compress_type = info.compress_type
            zi.external_attr = info.external_attr
            dst.writestr(zi, src.read(info.filename))
    return out.getvalue()


def read_parts(data: bytes) -> dict[str, bytes]:
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return {name: archive.read(name) for name in archive.namelist()}


def write_parts(parts: dict[str, bytes]) -> bytes:
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in parts.items():
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data)
    return out.getvalue()


def _next_rid(rels: etree._Element) -> str:
    used = set()
    for child in rels:
        rid = child.get("Id", "")
        if rid.startswith("rId") and rid[3:].isdigit():
            used.add(int(rid[3:]))
    return f"rId{max(used, default=0) + 1}"


def _add_rel(
    rels: etree._Element, rid: str, rel_type: str, target: str, *, external: bool = False
) -> None:
    child = etree.SubElement(rels, f"{{{PKG_REL}}}Relationship")
    child.set("Id", rid)
    child.set("Type", rel_type)
    child.set("Target", target)
    if external:
        child.set("TargetMode", "External")


def _add_override(parts: dict[str, bytes], part_name: str, content_type: str) -> None:
    root = etree.fromstring(parts["[Content_Types].xml"])
    for child in root:
        if child.get("PartName") == part_name:
            child.set("ContentType", content_type)
            break
    else:
        child = etree.SubElement(root, f"{{{CT}}}Override")
        child.set("PartName", part_name)
        child.set("ContentType", content_type)
    parts["[Content_Types].xml"] = etree.tostring(
        root, xml_declaration=True, encoding="UTF-8", standalone=True
    )


def _xml(root: etree._Element) -> bytes:
    return etree.tostring(root, xml_declaration=True, encoding="UTF-8", standalone=True)


def _insert_before_sect(body: etree._Element, element: etree._Element) -> None:
    sect = body.find(f"{{{W}}}sectPr")
    if sect is not None:
        sect.addprevious(element)
    else:
        body.append(element)


def _docx_paragraph(inner: str) -> etree._Element:
    return etree.fromstring(
        f'<w:p xmlns:w="{W}" xmlns:r="{R}" xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing" '
        f'xmlns:a="{A}" xmlns:c="{C}">{inner}</w:p>'
    )


def build_docx(case: int) -> bytes:
    marker = f"CASE-DOCX-{case:03d}"
    parts = read_parts((SEEDS / "docx-02-enhanced.docx").read_bytes())
    doc = etree.fromstring(parts["word/document.xml"])
    body = doc.find(f"{{{W}}}body")
    assert body is not None
    rels = etree.fromstring(parts["word/_rels/document.xml.rels"])
    rid_link = _next_rid(rels)
    _add_rel(
        rels,
        rid_link,
        f"{R}/hyperlink",
        f"https://example.com/{marker}",
        external=True,
    )
    rid_chart = _next_rid(rels)
    _add_rel(rels, rid_chart, f"{R}/chart", "charts/chart1.xml")
    parts["word/_rels/document.xml.rels"] = _xml(rels)
    parts["word/charts/chart1.xml"] = CHART_XML.encode()
    _add_override(
        parts,
        "/word/charts/chart1.xml",
        "application/vnd.openxmlformats-officedocument.drawingml.chart+xml",
    )

    filler = (
        f"{marker}: Alice Chen approved this line for John Smith. "
        "The counterparty is Example Bio GmbH, contract CU-2026-001. "
    ) * (1 + case % 3)
    _insert_before_sect(
        body,
        _docx_paragraph(f'<w:r><w:t xml:space="preserve">{escape(filler)}</w:t></w:r>'),
    )
    _insert_before_sect(
        body,
        etree.fromstring(
            f'<w:sdt xmlns:w="{W}"><w:sdtPr><w:alias w:val="{marker} Field"/></w:sdtPr>'
            f'<w:sdtContent><w:p><w:r><w:t xml:space="preserve">Controlled field {marker}</w:t></w:r></w:p>'
            "</w:sdtContent></w:sdt>"
        ),
    )
    _insert_before_sect(
        body,
        _docx_paragraph(
            f'<w:r><w:t xml:space="preserve">Reference: </w:t></w:r>'
            f'<w:hyperlink r:id="{rid_link}"><w:r><w:t>{marker} evidence</w:t></w:r></w:hyperlink>'
        ),
    )
    _insert_before_sect(
        body,
        _docx_paragraph(
            f'<w:r><w:drawing><wp:inline distT="0" distB="0" distL="0" distR="0">'
            '<wp:extent cx="4572000" cy="2743200"/><wp:effectExtent l="0" t="0" r="0" b="0"/>'
            f'<wp:docPr id="{9000 + case}" name="Chart {case}"/><wp:cNvGraphicFramePr/>'
            f'<a:graphic><a:graphicData uri="{C}"><c:chart r:id="{rid_chart}"/>'
            "</a:graphicData></a:graphic></wp:inline></w:drawing></w:r>"
        ),
    )
    parts["word/document.xml"] = _xml(doc)
    return normalize_zip(write_parts(parts))


def build_pptx(case: int) -> bytes:
    marker = f"CASE-PPTX-{case:03d}"
    parts = read_parts((SEEDS / "pptx-02-enhanced.pptx").read_bytes())
    slide_name = "ppt/slides/slide1.xml"
    rels_name = "ppt/slides/_rels/slide1.xml.rels"
    slide = etree.fromstring(parts[slide_name])
    rels = etree.fromstring(parts[rels_name])
    sp_tree = slide.find(f".//{{{P}}}cSld/{{{P}}}spTree")
    assert sp_tree is not None
    rid_link = _next_rid(rels)
    _add_rel(rels, rid_link, f"{R}/hyperlink", f"https://example.com/{marker}", external=True)
    rid_chart = _next_rid(rels)
    _add_rel(rels, rid_chart, f"{R}/chart", "../charts/chart1.xml")
    parts[rels_name] = _xml(rels)
    parts["ppt/charts/chart1.xml"] = CHART_XML.encode()
    _add_override(
        parts,
        "/ppt/charts/chart1.xml",
        "application/vnd.openxmlformats-officedocument.drawingml.chart+xml",
    )

    footer = etree.fromstring(
        f'<p:sp xmlns:p="{P}" xmlns:a="{A}"><p:nvSpPr><p:cNvPr id="{9100 + case}" name="Footer {case}"/>'
        "<p:cNvSpPr/><p:nvPr><p:ph type=\"ftr\" sz=\"quarter\"/></p:nvPr></p:nvSpPr><p:spPr/>"
        f"<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang=\"en-US\" dirty=\"0\"/>"
        f"<a:t>{marker} — Confidential</a:t></a:r></a:p></p:txBody></p:sp>"
    )
    sp_tree.append(footer)

    link_sp = etree.fromstring(
        f'<p:sp xmlns:p="{P}" xmlns:a="{A}" xmlns:r="{R}">'
        f'<p:nvSpPr><p:cNvPr id="{9200 + case}" name="Link {case}"/><p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr>'
        '<p:spPr><a:xfrm><a:off x="457200" y="4572000"/><a:ext cx="3657600" cy="457200"/></a:xfrm>'
        '<a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>'
        '<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang="en-US" dirty="0">'
        f'<a:hlinkClick r:id="{rid_link}"/></a:rPr><a:t>{marker} evidence link</a:t></a:r></a:p>'
        "</p:txBody></p:sp>"
    )
    sp_tree.append(link_sp)

    chart_frame = etree.fromstring(
        f'<p:graphicFrame xmlns:p="{P}" xmlns:a="{A}" xmlns:c="{C}" xmlns:r="{R}">'
        f'<p:nvGraphicFramePr><p:cNvPr id="{9300 + case}" name="Chart {case}"/><p:cNvGraphicFramePr/><p:nvPr/>'
        '</p:nvGraphicFramePr><p:xfrm><a:off x="4572000" y="914400"/><a:ext cx="4572000" cy="2743200"/>'
        f'</p:xfrm><a:graphic><a:graphicData uri="{C}"><c:chart r:id="{rid_chart}"/>'
        "</a:graphicData></a:graphic></p:graphicFrame>"
    )
    sp_tree.append(chart_frame)

    note = etree.fromstring(
        f'<p:sp xmlns:p="{P}" xmlns:a="{A}">'
        f'<p:nvSpPr><p:cNvPr id="{9400 + case}" name="Case note {case}"/><p:cNvSpPr txBox="1"/><p:nvPr/>'
        '</p:nvSpPr><p:spPr><a:xfrm><a:off x="457200" y="5029200"/><a:ext cx="10058400" cy="685800"/>'
        '</a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></p:spPr>'
        '<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang="en-US" dirty="0"/>'
        f"<a:t>{marker}: Alice Chen prepared this case for John Smith.</a:t></a:r></a:p>"
        "</p:txBody></p:sp>"
    )
    sp_tree.append(note)
    parts[slide_name] = _xml(slide)
    return normalize_zip(write_parts(parts))


def _add_xlsx_textbox(parts: dict[str, bytes], marker: str, case: int) -> None:
    drawing_names = [n for n in parts if n.startswith("xl/drawings/drawing") and n.endswith(".xml")]
    if not drawing_names:
        raise RuntimeError("openpyxl did not create a drawing part for the image")
    name = drawing_names[0]
    root = etree.fromstring(parts[name])
    anchor = etree.fromstring(
        f'<xdr:twoCellAnchor xmlns:xdr="{XDR}" xmlns:a="{A}">'
        "<xdr:from><xdr:col>9</xdr:col><xdr:colOff>0</xdr:colOff><xdr:row>2</xdr:row><xdr:rowOff>0</xdr:rowOff></xdr:from>"
        "<xdr:to><xdr:col>15</xdr:col><xdr:colOff>0</xdr:colOff><xdr:row>8</xdr:row><xdr:rowOff>0</xdr:rowOff></xdr:to>"
        f'<xdr:sp macro="" textlink=""><xdr:nvSpPr><xdr:cNvPr id="{9500 + case}" name="TextBox {case}"/>'
        '<xdr:cNvSpPr txBox="1"/></xdr:nvSpPr><xdr:spPr><a:xfrm><a:off x="0" y="0"/>'
        '<a:ext cx="2286000" cy="914400"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom>'
        '</xdr:spPr><xdr:txBody><a:bodyPr vertOverflow="clip" wrap="square"/><a:lstStyle/>'
        f'<a:p><a:r><a:rPr lang="en-US"/><a:t>{marker} text box</a:t></a:r></a:p></xdr:txBody>'
        "</xdr:sp><xdr:clientData/></xdr:twoCellAnchor>"
    )
    root.append(anchor)
    parts[name] = _xml(root)


def build_xlsx(case: int) -> bytes:
    marker = f"CASE-XLSX-{case:03d}"
    wb = Workbook()
    ws = wb.active
    ws.title = "Data"
    ws["A1"] = marker
    ws["A2"], ws["B2"] = "Name", "Alice Chen"
    ws["A3"], ws["B3"] = "Company", "Example Bio GmbH"
    ws["A4"], ws["B4"] = "Contract", "CU-2026-001"
    ws["A5"], ws["B5"] = "Reviewer", "John Smith"
    ws["D4"] = "Merged header cell"
    ws.merge_cells("D4:F4")
    ws["A12"] = "Evidence link"
    ws["A12"].hyperlink = f"https://example.com/{marker}"
    ws["B2"].comment = Comment("Please verify this counterparty", "Alice Chen")
    ws.oddHeader.center.text = f"&CConfidential {marker}"
    ws.oddFooter.left.text = f"&LGenerated fidelity case {case:03d}"
    for row in range(1, 6 + case % 7):
        ws.cell(row=20 + row, column=1, value=f"{marker} row {row}")
        ws.cell(row=20 + row, column=2, value=row * 11 + case)

    hidden = wb.create_sheet("HiddenStuff")
    hidden["A1"] = f"{marker} hidden sheet payload"
    hidden.sheet_state = "veryHidden"

    chart_ws = wb.create_sheet("ChartData")
    chart_ws["A1"], chart_ws["B1"] = "Month", "Cases"
    for idx, (month, value) in enumerate((("Jan", 3), ("Feb", 5), ("Mar", 8), ("Apr", 4)), start=2):
        chart_ws.cell(row=idx, column=1, value=month)
        chart_ws.cell(row=idx, column=2, value=value + case % 4)
    chart = BarChart()
    chart.title = f"Case volume {marker}"
    chart.add_data(Reference(chart_ws, min_col=2, min_row=1, max_row=5), titles_from_data=True)
    chart.set_categories(Reference(chart_ws, min_col=1, min_row=2, max_row=5))
    chart_ws.add_chart(chart, "E2")

    png = io.BytesIO()
    PILImage.new("RGB", (64, 64), (30, 90, 170)).save(png, format="PNG")
    png.seek(0)
    ws.add_image(XLImage(png), "H2")

    buf = io.BytesIO()
    wb.save(buf)
    parts = read_parts(buf.getvalue())
    _add_xlsx_textbox(parts, marker, case)
    return normalize_zip(write_parts(parts))


BUILDERS = {"docx": build_docx, "xlsx": build_xlsx, "pptx": build_pptx}


def main() -> int:
    sys.path.insert(0, str(REPO))
    from tools.verify_corpus import REQUIRED, actual_features

    rows: list[dict[str, str]] = []
    for fmt, builder in BUILDERS.items():
        fmt_dir = CORPUS / fmt
        fmt_dir.mkdir(parents=True, exist_ok=True)
        for case in range(1, N + 1):
            data = builder(case)
            path = fmt_dir / f"{fmt}-{case:03d}.{fmt}"
            path.write_bytes(data)
            found = actual_features(path)
            missing = [feature for feature in REQUIRED[fmt] if feature not in found]
            if missing:
                raise SystemExit(f"{path.relative_to(REPO)}: generator missed {missing}")
            with zipfile.ZipFile(io.BytesIO(data)) as archive:
                parts = len(archive.infolist())
            rows.append(
                {
                    "path": path.relative_to(REPO).as_posix(),
                    "format": fmt,
                    "sha256": hashlib.sha256(data).hexdigest(),
                    "size_bytes": str(len(data)),
                    "parts": str(parts),
                    "features": ";".join(sorted(found)),
                    "generator_version": GENERATOR_VERSION,
                    "seed": {
                        "docx": "seeds/docx-02-enhanced.docx",
                        "pptx": "seeds/pptx-02-enhanced.pptx",
                        "xlsx": "openpyxl + drawing patching",
                    }[fmt],
                }
            )
        print(f"{fmt}: {N} files")
    rows.sort(key=lambda row: row["path"])
    with (CORPUS / "manifest.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    from tools.verify_corpus import COVERAGE, coverage_table

    COVERAGE.write_text(coverage_table(), encoding="utf-8")
    print(f"manifest: {CORPUS / 'manifest.csv'} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
